// Extracts the few music symbols the staff view needs from the Bravura font (SIL Open Font License,
// see licenses/Bravura-OFL.txt) into js/glyphs.js as SVG path data, so the app draws real engraved
// clefs, noteheads and accidentals without loading a 900 KB font.
// Usage: node tools/make-glyphs.mjs <path-to-Bravura.otf> <path-to-Bravura.json>
// Units: 1 = one staff space (the gap between two staff lines); y grows downward; baseline at y = 0,
// which SMuFL puts on the staff line a clef names (G line, F line, middle-C line) and at the centre of a notehead.
import opentype from 'opentype.js';
import fs from 'node:fs';
import path from 'node:path';

const [otf, meta] = process.argv.slice(2);
if (!otf || !meta) { console.error('usage: node tools/make-glyphs.mjs <Bravura.otf> <Bravura.json>'); process.exit(1); }
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const font = opentype.parse(fs.readFileSync(otf).buffer);
const metadata = JSON.parse(fs.readFileSync(meta, 'utf8'));

const WANT = {
  gClef: 0xE050, gClef8vb: 0xE052, fClef: 0xE062, cClef: 0xE05C,
  noteheadBlack: 0xE0A4, noteheadWhole: 0xE0A2, noteheadHalf: 0xE0A3,
  accidentalSharp: 0xE262, accidentalFlat: 0xE260, accidentalNatural: 0xE261,
  brace: 0xE000,
};

const out = {};
for (const [name, cp] of Object.entries(WANT)) {
  const glyph = font.charToGlyph(String.fromCodePoint(cp));
  if (!glyph || glyph.index === 0) throw new Error('missing glyph ' + name);
  // font size 4 => 1 em = 4 units = 4 staff spaces, i.e. 1 unit = 1 staff space (SMuFL convention)
  const d = glyph.getPath(0, 0, 4).toPathData(3);
  out[name] = { d, w: metadata.glyphAdvanceWidths[name] ?? glyph.advanceWidth / font.unitsPerEm * 4, box: metadata.glyphBBoxes[name] };
}
const ed = metadata.engravingDefaults;
const engraving = { staffLine: ed.staffLineThickness, ledger: ed.legerLineThickness, ledgerExt: ed.legerLineExtension, stem: ed.stemThickness };

const js = `// Generated by tools/make-glyphs.mjs from Bravura ${metadata.fontVersion} (SIL Open Font License 1.1,
// Copyright © 2015 Steinberg Media Technologies GmbH; see licenses/Bravura-OFL.txt). Do not edit.
// Units are staff spaces, y down, baseline at 0.
export const ENGRAVING = ${JSON.stringify(engraving)};
export const GLYPHS = ${JSON.stringify(out, null, 0).replace(/},"/g, '},\n  "')};
`;
fs.writeFileSync(path.join(root, 'js/glyphs.js'), js);
console.log(`wrote js/glyphs.js: ${Object.keys(out).length} glyphs, ${(js.length / 1024).toFixed(1)} KB`);
